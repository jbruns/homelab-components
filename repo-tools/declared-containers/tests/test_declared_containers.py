"""Tests for the declared-containers generator, at its render() and CLI seams."""

import subprocess
import sys
import textwrap
from pathlib import Path

import pytest
from homelab_hosts import load_hosts

import homelab_declared_containers as declared_containers

HOSTS_YAML = """
    version: 1
    hosts:
      truenas:
        stack_root: tn
        deployer: doco-cd
        capabilities: [truenas, zfs]
"""

FIXTURE = {
    "hosts.yaml": HOSTS_YAML,
    "tn/_baseline.yaml": """
        services:
          baseline:
            restart: unless-stopped
    """,
    "tn/edge/compose.yaml": """
        services:
          traefik:
            extends: {file: ../_baseline.yaml, service: baseline}
            container_name: traefik
            labels:
              tier: critical
              startup-order: "0"
    """,
    "tn/app/compose.yaml": """
        include:
          - ./web/service.yaml
          - path: [./db/service.yaml]
    """,
    "tn/app/web/service.yaml": """
        services:
          web:
            labels: ["tier=warning", "startup-order=2"]
          web-exporter:
            container_name: web-exporter
            labels: {tier: info}
    """,
    "tn/app/db/service.yaml": """
        services:
          db:
            container_name: app-db
            labels: {tier: "critical"}
    """,
}

EXPECTED = """\
# HELP homeops_container_declared A Service that tn/ declares, whose container should be running. Generated by homelab-declared-containers; do not edit.
# TYPE homeops_container_declared gauge
homeops_container_declared{stack="app",service="db",name="app-db",tier="critical"} 1
homeops_container_declared{stack="app",service="web",name="app-web-1",tier="warning"} 1
homeops_container_declared{stack="app",service="web-exporter",name="web-exporter",tier="info"} 1
homeops_container_declared{stack="edge",service="traefik",name="traefik",tier="critical"} 1
"""  # noqa: E501

OUT = "monitoring/node-exporter/declared_containers.prom"


def write(root: Path, files: dict[str, str]) -> None:
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(textwrap.dedent(text).lstrip("\n"))


def run(*args: str, cwd: Path | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "homelab_declared_containers", *args], capture_output=True, text=True, cwd=cwd
    )


@pytest.fixture
def root(tmp_path):
    write(tmp_path, FIXTURE)
    return tmp_path


def host(root: Path, name: str = "truenas"):
    return load_hosts(root)[name]


def test_render_lists_every_service_of_every_stack(root):
    assert declared_containers.render(host(root)) == EXPECTED


def test_a_retired_stack_or_removed_service_is_no_longer_declared(root):
    (root / "tn/edge/compose.yaml").unlink()
    write(root, {"tn/app/web/service.yaml": "services:\n  web:\n    labels: {tier: warning}\n"})
    text = declared_containers.render(host(root))
    assert 'stack="edge"' not in text and 'service="web-exporter"' not in text
    assert 'service="web"' in text


@pytest.mark.parametrize(
    "service, problem",
    [
        ("web:\n    container_name: ${NAME}\n    labels: {tier: info}", "web: container_name"),
        ("web:\n    labels: {tier: info, other: x}\n    image: x\n  bare:\n    image: y", "bare: no tier label"),
    ],
)
def test_render_rejects_what_it_cannot_resolve(root, service, problem):
    write(root, {"tn/app/web/service.yaml": "services:\n  " + service + "\n"})
    with pytest.raises(declared_containers.GeneratorError, match=problem):
        declared_containers.render(host(root))


def test_render_rejects_a_missing_include(root):
    (root / "tn/app/web/service.yaml").unlink()
    with pytest.raises(declared_containers.GeneratorError, match="includes missing .*web/service.yaml"):
        declared_containers.render(host(root))


def test_check_reports_a_stale_file_and_write_fixes_it(root):
    out = root / "declared.prom"
    r = run("--root", str(root), "--out", str(out), "--check")
    assert r.returncode == 1 and "stale" in r.stdout
    assert run("--root", str(root), "--out", str(out)).returncode == 0
    assert out.read_text() == EXPECTED
    assert run("--root", str(root), "--out", str(out), "--check").returncode == 0


def test_writes_to_the_stack_root_by_default_from_the_repo_containing_the_working_directory(root):
    assert run(cwd=root / "tn/app").returncode == 0
    assert (root / "tn" / OUT).read_text() == EXPECTED


@pytest.fixture
def two_hosts(root):
    """The fixture plus a second Host, without capabilities, whose stack root is nested."""
    write(
        root,
        {
            "hosts.yaml": HOSTS_YAML
            + "      nc8kg1101:\n        stack_root: sites/nc8kg1101\n        deployer: doco-cd\n"
            + "        capabilities: []\n",
            "sites/nc8kg1101/ops/compose.yaml": """
                services:
                  apprise:
                    container_name: apprise
                    labels: {tier: warning}
            """,
        },
    )
    return root


def test_each_host_declares_only_its_own_stacks(two_hosts):
    assert declared_containers.render(host(two_hosts)) == EXPECTED
    other = declared_containers.render(host(two_hosts, "nc8kg1101"))
    assert "A Service that sites/nc8kg1101/ declares" in other
    assert other.splitlines()[2:] == [
        'homeops_container_declared{stack="ops",service="apprise",name="apprise",tier="warning"} 1'
    ]


def test_writes_and_checks_one_file_per_host(two_hosts):
    r = run("--root", str(two_hosts), "--check")
    assert r.returncode == 1
    assert f"tn/{OUT}: stale" in r.stdout and f"sites/nc8kg1101/{OUT}: stale" in r.stdout
    assert run("--root", str(two_hosts)).returncode == 0
    assert (two_hosts / "tn" / OUT).read_text() == EXPECTED
    assert 'stack="ops"' in (two_hosts / "sites/nc8kg1101" / OUT).read_text()
    assert run("--root", str(two_hosts), "--check").returncode == 0


def test_host_picks_one_host(two_hosts):
    assert run("--root", str(two_hosts), "--host", "nc8kg1101").returncode == 0
    assert (two_hosts / "sites/nc8kg1101" / OUT).exists() and not (two_hosts / "tn" / OUT).exists()


def test_out_needs_a_single_host(two_hosts):
    r = run("--root", str(two_hosts), "--out", "x.prom")
    assert r.returncode == 2 and "--out needs --host" in r.stderr
    assert run("--root", str(two_hosts), "--host", "truenas", "--out", str(two_hosts / "x.prom")).returncode == 0


def test_reports_an_invalid_hosts_file(root):
    write(root, {"hosts.yaml": "version: 2\nhosts: {}\n"})
    r = run("--root", str(root))
    assert r.returncode == 1 and "version" in r.stdout

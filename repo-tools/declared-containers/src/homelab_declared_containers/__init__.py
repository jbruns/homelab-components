"""Generate the Services each Host declares, as a node-exporter textfile.

ContainerDown fires for a declared Service whose container is not running, so a Stack or Service removed from
git stops being expected as soon as monitoring is Deployed. Edit the Compose files and rerun this; never edit the
output. See README.md.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

import yaml
from homelab_hosts import Host, HostsError, find_repo_root, load_hosts

__all__ = ["METRIC", "OUT", "GeneratorError", "compose_files", "declared", "labels_of", "main", "render"]

# Where each Host's file goes, relative to its stack root.
OUT = "monitoring/node-exporter/declared_containers.prom"
METRIC = "homeops_container_declared"
VARIABLE = re.compile(r"\$\{?[A-Za-z_]")


class GeneratorError(Exception):
    pass


def compose_files(entry: Path) -> list[Path]:
    """A Stack's entry file plus everything it includes, recursively (as validate reads them)."""
    seen: list[Path] = []
    todo = [entry]
    while todo:
        f = todo.pop()
        if f in seen:
            continue
        if not f.exists():
            raise GeneratorError(f"{entry}: includes missing {f}")
        seen.append(f)
        for inc in (yaml.safe_load(f.read_text()) or {}).get("include") or []:
            paths = inc.get("path") if isinstance(inc, dict) else inc
            todo += [(f.parent / p).resolve() for p in ([paths] if isinstance(paths, str) else paths or [])]
    return seen


def labels_of(service: dict) -> dict:
    labels = service.get("labels") or {}
    if isinstance(labels, list):
        labels = dict(item.split("=", 1) if "=" in item else (item, "") for item in labels)
    return {k: str(v) for k, v in labels.items()}


def declared(host: Host) -> list[tuple[str, str, str, str]]:
    """(stack, service, container name, tier) of each Service in <stack root>/<stack>/compose.yaml."""
    rows, problems = [], []
    for entry in sorted(host.path.glob("*/compose.yaml")):
        # doco-cd uses the folder name as the Compose project name.
        stack = entry.parent.name
        for f in compose_files(entry):
            for service, spec in ((yaml.safe_load(f.read_text()) or {}).get("services") or {}).items():
                spec = spec or {}
                name = str(spec.get("container_name") or f"{stack}-{service}-1")
                tier = labels_of(spec).get("tier", "")
                where = f"{host.stack_root}/{f.relative_to(host.path)}" if f.is_relative_to(host.path) else str(f)
                where += f": {service}"
                if VARIABLE.search(name):
                    problems.append(f"{where}: container_name {name!r} must not use variables")
                if not tier or VARIABLE.search(tier):
                    problems.append(f"{where}: no tier label (or it uses variables)")
                rows.append((stack, service, name, tier))
    if problems:
        raise GeneratorError("\n".join(problems))
    return sorted(rows)


def render(host: Host) -> str:
    header = (
        f"# HELP {METRIC} A Service that {host.stack_root}/ declares, whose container should be running. "
        "Generated by homelab-declared-containers; do not edit.\n"
        f"# TYPE {METRIC} gauge\n"
    )
    return header + "".join(
        f'{METRIC}{{stack="{s}",service="{v}",name="{n}",tier="{t}"}} 1\n' for s, v, n, t in declared(host)
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="homelab-declared-containers",
        description="Write the containers each Host declares, for ContainerDown.",
    )
    parser.add_argument("--check", action="store_true", help="fail if an output file is stale")
    parser.add_argument("--root", type=Path, help="repository root (default: the one holding hosts.yaml above here)")
    parser.add_argument("--host", help="only this Host (default: every Host in hosts.yaml)")
    parser.add_argument("--out", type=Path, help=f"output file for --host (default: <stack root>/{OUT})")
    args = parser.parse_args(argv)
    try:
        hosts = load_hosts(args.root or find_repo_root())
        selected = [hosts.pick(args.host)] if args.host else list(hosts.values())
    except HostsError as exc:
        print(exc)
        return 1
    if args.out and len(selected) > 1:
        parser.error("--out needs --host when hosts.yaml declares more than one Host")
    stale = False
    for host in selected:
        out = args.out or host.path / OUT
        try:
            text = render(host)
        except GeneratorError as exc:
            print(exc)
            return 1
        if not args.check:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text)
        elif not out.exists() or out.read_text() != text:
            print(f"{out if args.out else f'{host.stack_root}/{OUT}'}: stale; run homelab-declared-containers")
            stale = True
    return 1 if stale else 0
